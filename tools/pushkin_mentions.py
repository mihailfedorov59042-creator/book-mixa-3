def identify(book, index, name, word):
    if book == '002001':
        if name == 'Курбский' and index in (1405,1880): return 'Курбский-старший'
        if name == 'Феодор' and index < 1000: return 'Феодор Иоаннович'
        if name == 'Димитрий Угличский' and (1300 <= index < 1960 or index == 1972 or index >= 2100): return 'Григорий Отрепьев'
        if name == 'Борис Годунов' and 1076 <= index <= 1128 and word.lower().startswith('годунов'): return 'Семён Годунов'
        if name == 'Гаврила Пушкин' and word.lower().startswith('пушкин') and index < 1200 and index != 937: return 'Афанасий Пушкин'
    return name

def speaker(book,i,label,cues):
    if book=='002006' and label=='дочь':return 'Русалочка' if i>=790 else 'Дочь мельника'
    if book=='002001':
        if label=='пушкин':return 'Афанасий Пушкин' if i<1140 else 'Гаврила Пушкин'
        if label=='все': return 'Ляхи' if i==2301 else 'Сторонники Самозванца'
        if label in {'один','другой','третий','первый','второй','четвертый','пятый','шестой'}:
            for low,high,person in [(157,283,'Народ'),(605,627,'Два стольника'),(750,855,'Приставы'),
                                    (2065,2076,'Бояре'),(2080,2092,'Воины'),(2125,2145,'Народ'),
                                    (2304,2330,'Ляхи'),(2485,2516,'Бояре'),(2794,2820,'Народ')]:
                if low<=i<=high:return person
    return cues.get(label)

def mark_mentions(bid,blocks,people):
    key=bid.removeprefix('push_s')
    ids={person[0]:f'c{i}' for i,person in enumerate(people)}
    cues={n.lower():n for n in ids}
    for name,labels in CUES.get(key,{}).items():
        assert name in ids,(key,name)
        cues.update({label.lower():name for label in labels.split('|')})
    names=sorted(ids,key=len,reverse=True)
    pattern=re.compile(r'(?<!\w)(?:'+'|'.join(f'(?P<n{i}>'+FORMS.get(n,re.escape(n))+')' for i,n in enumerate(names))+r')(?!\w)',re.I)
    def wrap(text,name):
        return f'<span class="ch" data-ch="{ids[name]}" role="button" tabindex="0">{text}</span>'
    for i,(kind,markup,*_) in enumerate(blocks):
        if kind in ('h1','str','va') or not markup:continue
        plain=re.sub('<[^>]*>','',markup)
        label=re.split(r'\s*\(|[.,]\s*$',plain,maxsplit=1)[0].strip().lower()
        cue=speaker(key,i,label,cues) if kind=='sp' or plain.endswith('.') and len(plain)<48 else None
        parts=re.split(r'(<[^>]+>)',markup)
        in_link=False
        for j,t in enumerate(parts):
            if t.startswith('<'):
                if t.startswith('<a '):in_link=True
                elif t=='</a>':in_link=False
                continue
            if not t or in_link:continue
            prefix=''
            if cue and t[:len(label)].lower()==label:
                prefix=wrap(t[:len(label)],cue);t=t[len(label):];cue=None
            def replace(m):
                name=names[int(m.lastgroup[1:])]
                # The author's signature, unlike the uncle and nephew in the drama.
                if key=='002001' and i==7:return m[0]
                return wrap(m[0],identify(key,i,name,m[0]))
            parts[j]=prefix+pattern.sub(replace,t)
        blocks[i][1]=''.join(parts)
